<?php

namespace Grafite\Maintenance\Commands;

use Illuminate\Console\Command as AppCommand;

class Updating extends AppCommand
{
    protected $signature = 'maintenance:updating {--retry=3600 : Seconds sent in the Retry-After header}';

    protected $description = 'Place an application in maintenance mode while updating';

    public function handle(): int
    {
        $index = public_path('index.php');
        $backup = public_path('index-bk.php');

        if (file_exists($backup)) {
            $this->error('The application is already in maintenance mode (public/index-bk.php exists). Run maintenance:live first.');

            return self::FAILURE;
        }

        copy($index, $backup);

        $retry = max(0, (int) $this->option('retry'));
        $html = file_get_contents(__DIR__ . '/../../resources/maintenance.html');

        file_put_contents($index, implode("\n", [
            '<?php',
            '// Generated by maintenance:updating. Restore the app with maintenance:live.',
            'http_response_code(503);',
            "header('Retry-After: {$retry}');",
            "header('Content-Type: text/html; charset=UTF-8');",
            '?>',
            $html,
        ]));

        $this->info('Application is now in maintenance mode');

        return self::SUCCESS;
    }
}
